"""Claude Code sessions, read from its transcript files (read-only).

Claude Code writes one JSON Lines file per session under a projects directory, one
folder per working directory. Each main session file becomes one or more docs with the
user/assistant dialogue. Sub-agent transcripts (`subagents/` folders and side-chain
records) are skipped by default: the main thread already contains what was asked of
them, and the final report of a delegated task is kept (see `keep_results_of`).
Plumbing such as system reminders, local command output and tool results is dropped.

Claude Code deletes old transcripts on its own (30 days by default), so the original
text is kept in the library once ingested.
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from ..projects import DEFAULT_RULES, ProjectRules
from ..store import ConnectorState
from .base import Batch, RawDoc, segment, truncate_middle

_STRIP = re.compile(
    r"<(system-reminder|memory-context)>.*?</\1>",
    re.DOTALL,
)
_SHORTEN = re.compile(
    r"<(local-command-stdout|local-command-stderr|bash-stdout|bash-stderr)>(.*?)</\1>",
    re.DOTALL,
)
_COMMAND = re.compile(
    r"<command-name>(.*?)</command-name>(?:.*?<command-args>(.*?)</command-args>)?", re.DOTALL
)
_TAGS = re.compile(r"</?(command-message|command-name|command-args|command-contents)>")
_SKIP_PREFIXES = ("Caveat: The messages below were generated by the user",)


class ClaudeCodeConnector:
    def __init__(
        self,
        name: str,
        options: dict[str, Any],
        *,
        max_segment_chars: int,
        default_project: str | None = None,
        project_rules: ProjectRules | None = None,
    ) -> None:
        self.name = name
        self.root = Path(os.path.expanduser(str(options["projects_dir"])))
        self.settle_seconds = float(options.get("settle_minutes", 30)) * 60
        self.include_subagents = bool(options.get("include_subagents", False))
        self.include_tool_calls = bool(options.get("include_tool_calls", True))
        self.max_tool_args = int(options.get("max_tool_args_chars", 200))
        self.keep_results_of = set(options.get("keep_results_of", ["Task", "Agent"]))
        self.max_kept_result = int(options.get("max_kept_result_chars", 3000))
        self.max_command_output = int(options.get("max_command_output_chars", 500))
        self.skip_entrypoints = set(options.get("skip_entrypoints", []))
        self.min_chars = int(options.get("min_chars", 400))
        self.project_aliases = dict(options.get("project_aliases", {}))
        self.rules = (project_rules or DEFAULT_RULES).with_aliases(self.project_aliases)
        self.skip_project_dirs = list(options.get("skip_project_dirs", []))
        """Globs on the project folder name (Claude Code's slug of the working directory)."""
        self.max_segment_chars = max_segment_chars
        self.default_project = default_project

    # -- discovery ---------------------------------------------------------------------

    def _files(self) -> list[Path]:
        if not self.root.is_dir():
            raise FileNotFoundError(f"Claude Code projects directory not found: {self.root}")
        files = sorted(self.root.rglob("*.jsonl"))
        if not self.include_subagents:
            files = [f for f in files if "subagents" not in f.relative_to(self.root).parts]
        if self.skip_project_dirs:
            files = [
                f
                for f in files
                if not any(
                    fnmatch.fnmatch(f.relative_to(self.root).parts[0], g)
                    for g in self.skip_project_dirs
                )
            ]
        return files

    def collect(
        self,
        state: ConnectorState,
        *,
        limit: int | None = None,
        sample: int | None = None,
        now: float | None = None,
    ) -> Batch:
        now = time.time() if now is None else now
        settled_before = now - self.settle_seconds
        cursor = float(state.cursor) if state.cursor and sample is None else 0.0
        candidates = []
        for path in self._files():
            try:
                mtime = path.stat().st_mtime
            except FileNotFoundError:  # deleted by Claude Code's own cleanup meanwhile
                continue
            if mtime > cursor:
                candidates.append((mtime, path))
        deferred = sum(1 for m, _ in candidates if m > settled_before)
        ready = sorted(
            (c for c in candidates if c[0] <= settled_before),
            reverse=sample is not None,
        )
        if sample is not None:
            ready = ready[:sample]
        elif limit is not None:
            ready = ready[:limit]
        docs: list[RawDoc] = []
        for _, path in ready:
            docs.extend(self._session_docs(path))
        next_cursor = repr(max(m for m, _ in ready)) if sample is None and ready else None
        return Batch(docs=docs, next_cursor=next_cursor, deferred=deferred)

    # -- parsing -----------------------------------------------------------------------

    def _session_docs(self, path: Path) -> list[RawDoc]:
        blocks: list[tuple[int, float, str]] = []
        title: str | None = None
        session_id = path.stem
        cwd: str | None = None
        entrypoint: str | None = None
        tool_names: dict[str, str] = {}
        try:
            handle = path.open(encoding="utf-8", errors="replace")
        except FileNotFoundError:
            return []
        with handle:
            for index, line in enumerate(handle):
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue  # a partially written last line
                if not isinstance(record, dict):
                    continue
                kind = record.get("type")
                if kind == "ai-title" and record.get("aiTitle"):
                    title = str(record["aiTitle"])
                    continue
                if kind == "summary" and record.get("summary") and not title:
                    title = str(record["summary"])
                    continue
                if kind not in ("user", "assistant"):
                    continue
                if record.get("isSidechain") and not self.include_subagents:
                    continue
                if record.get("isMeta"):
                    continue
                session_id = record.get("sessionId") or session_id
                cwd = record.get("cwd") or cwd
                entrypoint = record.get("entrypoint") or entrypoint
                stamp = _timestamp(record.get("timestamp"))
                if stamp is None:
                    continue
                text = self._render(record, stamp, tool_names)
                if text:
                    blocks.append((index, stamp, text))
        if not blocks or entrypoint in self.skip_entrypoints:
            return []
        if sum(len(b[2]) for b in blocks) < self.min_chars:
            return []  # trivial sessions (a single slash command, "hi") are not worth a call
        project = self.rules.project_for(cwd, session_file=path) or self.default_project
        parts = segment(blocks, self.max_segment_chars)
        docs = []
        for number, part in enumerate(parts, 1):
            part_title = title
            if part_title and len(parts) > 1:
                part_title = f"{part_title} (part {number}/{len(parts)})"
            docs.append(
                RawDoc(
                    external_id=f"{session_id}#{part[0][0]}",
                    occurred_at=datetime.fromtimestamp(part[-1][1], UTC),
                    text="\n".join(b[2] for b in part),
                    title_hint=part_title,
                    project_hint=project,
                    original_ref=f"claude-code-session:{session_id}",
                    meta={
                        "entrypoint": entrypoint or "unknown",
                        "part": number,
                        "parts": len(parts),
                    },
                )
            )
        return docs

    def _render(self, record: dict[str, Any], stamp: float, tool_names: dict[str, str]) -> str:
        role = record["type"]
        when = datetime.fromtimestamp(stamp, UTC).strftime("%Y-%m-%d %H:%M")
        content = (record.get("message") or {}).get("content")
        if isinstance(content, str):
            content = [{"type": "text", "text": content}]
        if not isinstance(content, list):
            return ""
        lines: list[str] = []
        for block in content:
            if not isinstance(block, dict):
                continue
            btype = block.get("type")
            if btype == "text":
                text = self._clean(str(block.get("text") or ""))
                if text:
                    lines.append(f"[{when}] {role}: {text}")
            elif btype == "tool_use" and role == "assistant":
                name = str(block.get("name") or "?")
                if block.get("id"):
                    tool_names[str(block["id"])] = name
                if self.include_tool_calls:
                    args = json.dumps(block.get("input", {}), ensure_ascii=False)
                    if len(args) > self.max_tool_args:
                        args = args[: self.max_tool_args] + "..."
                    lines.append(f"[{when}] tool call: {name} {args}")
            elif btype == "tool_result":
                name = tool_names.get(str(block.get("tool_use_id")), "")
                if name in self.keep_results_of:
                    result = _flatten(block.get("content"))
                    if result:
                        result = truncate_middle(result, self.max_kept_result)
                        lines.append(f"[{when}] {name} result: {result}")
        return "\n".join(lines)

    def _clean(self, text: str) -> str:
        if text.startswith(_SKIP_PREFIXES):
            return ""
        text = _STRIP.sub("", text)
        text = _SHORTEN.sub(
            lambda m: "(output) " + truncate_middle(m.group(2).strip(), self.max_command_output),
            text,
        )
        command = _COMMAND.search(text)
        if command:
            args = (command.group(2) or "").strip()
            text = f"(command) {command.group(1).strip()} {args}".strip()
        return _TAGS.sub("", text).strip()


def _timestamp(value: Any) -> float | None:
    if isinstance(value, (int, float)):
        return float(value) / (1000 if value > 1e12 else 1)
    if isinstance(value, str) and value:
        try:
            return datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
        except ValueError:
            return None
    return None


def _flatten(content: Any) -> str:
    if isinstance(content, str):
        return content.strip()
    if isinstance(content, list):
        return "\n".join(
            str(b.get("text", ""))
            for b in content
            if isinstance(b, dict) and b.get("type") == "text"
        ).strip()
    return ""
