"""Claude Code connector against synthetic transcript files."""

from __future__ import annotations

import json
import os
from pathlib import Path

from jezero.connectors.claude_code import ClaudeCodeConnector
from jezero.store import ConnectorState

NOW = 2_000_000_000.0
T0 = "2033-05-18T00:00:00Z"  # before NOW


def write_session(path: Path, records: list[dict], mtime: float) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r) + "\n" for r in records) + '{"partial": ')
    os.utime(path, (mtime, mtime))


def base(**kw) -> dict:
    rec = {
        "sessionId": "sess-1",
        "timestamp": T0,
        "cwd": "/work/projects/billing-api/.worktrees/x",
        "entrypoint": "cli",
    }
    rec.update(kw)
    return rec


def make_tree(root: Path) -> None:
    records = [
        {"type": "ai-title", "aiTitle": "Fix flaky migration", "sessionId": "sess-1"},
        base(type="user", message={"role": "user", "content": "Why does the migration fail?"}),
        base(
            type="user",
            message={
                "role": "user",
                "content": "Caveat: The messages below were generated by the user while ...",
            },
        ),
        base(
            type="user",
            message={
                "role": "user",
                "content": "<command-name>/model</command-name>\n<command-args>opus</command-args>",
            },
        ),
        base(
            type="user",
            message={
                "role": "user",
                "content": "<local-command-stdout>" + "x" * 5000 + "</local-command-stdout>",
            },
        ),
        base(type="user", isMeta=True, message={"role": "user", "content": "meta noise"}),
        base(
            type="assistant",
            message={
                "role": "assistant",
                "content": [
                    {"type": "thinking", "thinking": "secret reasoning"},
                    {
                        "type": "text",
                        "text": "Let me check.<system-reminder>ignore</system-reminder>",
                    },
                    {
                        "type": "tool_use",
                        "id": "t1",
                        "name": "Bash",
                        "input": {"command": "pytest"},
                    },
                    {"type": "tool_use", "id": "t2", "name": "Task", "input": {"prompt": "audit"}},
                ],
            },
        ),
        base(
            type="user",
            message={
                "role": "user",
                "content": [
                    {"type": "tool_result", "tool_use_id": "t1", "content": "bash noise " * 50},
                    {
                        "type": "tool_result",
                        "tool_use_id": "t2",
                        "content": [{"type": "text", "text": "Audit: lock timeout in step 3"}],
                    },
                ],
            },
        ),
        base(type="assistant", isSidechain=True, message={"role": "assistant", "content": "side"}),
        base(type="attachment", attachment={"x": 1}),
    ]
    write_session(root / "-work-projects-billing-api" / "sess-1.jsonl", records, NOW - 7200)
    write_session(
        root / "-work-projects-billing-api" / "sess-1" / "subagents" / "agent-a.jsonl",
        [base(type="user", message={"role": "user", "content": "subagent prompt"})],
        NOW - 7200,
    )
    write_session(
        root / "-work" / "sess-live.jsonl",
        [base(type="user", sessionId="sess-live", message={"role": "user", "content": "hi"})],
        NOW - 60,
    )


def test_collect_main_sessions_only_and_clean(tmp_path: Path) -> None:
    make_tree(tmp_path)
    conn = ClaudeCodeConnector(
        "agent-claude", {"projects_dir": str(tmp_path), "min_chars": 0}, max_segment_chars=20_000
    )
    batch = conn.collect(ConnectorState("agent-claude"), now=NOW)
    assert batch.deferred == 1
    assert [d.external_id for d in batch.docs] == ["sess-1#1"]
    doc = batch.docs[0]
    text = doc.text
    assert doc.title_hint == "Fix flaky migration"
    assert doc.project_hint == "billing-api"
    assert doc.original_ref == "claude-code-session:sess-1"
    assert "Why does the migration fail?" in text
    assert "(command) /model opus" in text
    assert "Caveat" not in text and "meta noise" not in text and "side" not in text
    assert "secret reasoning" not in text and "ignore" not in text
    assert "bash noise" not in text and "subagent prompt" not in text
    assert 'tool call: Bash {"command": "pytest"}' in text
    assert "Task result: Audit: lock timeout in step 3" in text
    assert len(text) < 2000  # local command output was shortened

    again = conn.collect(ConnectorState("agent-claude", cursor=batch.next_cursor), now=NOW)
    assert again.docs == []


def test_trivial_sessions_are_skipped(tmp_path: Path) -> None:
    write_session(
        tmp_path / "-w" / "tiny.jsonl",
        [base(type="user", sessionId="tiny", message={"role": "user", "content": "/fast"})],
        NOW - 7200,
    )
    conn = ClaudeCodeConnector("c", {"projects_dir": str(tmp_path)}, max_segment_chars=20_000)
