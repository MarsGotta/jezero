"""Write the generated reference pages from the code.

    uv run python scripts/make_reference.py          # write docs/reference/{cli,configuration}.md
    uv run python scripts/make_reference.py --check  # CI: fail if they are out of date

The command reference comes from the argparse parsers of `jezero` and of the client core,
the configuration reference from the pydantic models and their attribute docstrings. Fix
the wording in the code, never in the generated files.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys
import types
import typing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
os.environ["COLUMNS"] = "88"  # stable help text

from pydantic import BaseModel  # noqa: E402
from pydantic.fields import FieldInfo  # noqa: E402
from pydantic_core import PydanticUndefined  # noqa: E402

from jezero import config as cfg  # noqa: E402
from jezero.cli import build_parser  # noqa: E402

OUT = ROOT / "docs" / "reference"
NOTE = "<!-- Generated by scripts/make_reference.py from the code: do not edit by hand. -->\n\n"


# ----------------------------------------------------------------------------- commands


HELP_GAPS = {"force": "replace an existing key on this computer"}
"""Help for client-core flags without help text (the core changes only with a release)."""


class _Captured(Exception):
    def __init__(self, parser: argparse.ArgumentParser) -> None:
        self.parser = parser


def client_parser() -> argparse.ArgumentParser:
    """The client core builds its parser inside main(): catch it at parse time."""
    path = ROOT / "clients" / "core" / "jezero_client.py"
    spec = importlib.util.spec_from_file_location("jezero_client_ref", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    original = argparse.ArgumentParser.parse_args

    def capture(self: argparse.ArgumentParser, *_: Any, **__: Any) -> Any:
        raise _Captured(self)

    argparse.ArgumentParser.parse_args = capture  # type: ignore[method-assign]
    try:
        module.main([])
    except _Captured as caught:
        return caught.parser
    finally:
        argparse.ArgumentParser.parse_args = original  # type: ignore[method-assign]
    raise SystemExit("could not capture the client parser")


def _subparsers(parser: argparse.ArgumentParser) -> list[tuple[str, argparse.ArgumentParser]]:
    for action in parser._actions:  # noqa: SLF001 - argparse has no public API for this
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            helps = {a.dest: a.help for a in action._choices_actions}  # noqa: SLF001
            return [(name, p) for name, p in action.choices.items() if name in helps]
    return []


def _help_of(parser: argparse.ArgumentParser, name: str) -> str:
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            for choice in action._choices_actions:  # noqa: SLF001
                if choice.dest == name:
                    return str(choice.help or "")
    return ""


def _arguments(parser: argparse.ArgumentParser) -> list[tuple[str, str, str]]:
    rows = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._HelpAction | argparse._SubParsersAction):  # noqa: SLF001
            continue
        if action.option_strings:
            name = ", ".join(f"`{o}`" for o in action.option_strings)
            if action.nargs != 0:
                metavar = action.metavar or action.dest.upper()
                name += f" `{metavar}`"
        else:
            name = f"`{action.metavar or action.dest}`"
            if action.nargs in ("+", "*"):
                name += " ..."
        default = action.default
        if action.choices and not isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            extra = "one of " + ", ".join(f"`{c}`" for c in action.choices)
        elif default not in (None, False, argparse.SUPPRESS) and action.nargs != 0:
            extra = f"default `{default}`"
        else:
            extra = ""
        text = " ".join(str(action.help or HELP_GAPS.get(action.dest, "")).split())
        text = f"{text} ({extra})" if text and extra else text or extra
        required = "required" if action.required or not action.option_strings else "optional"
        rows.append((name, required, text))
    return rows


def _anchor(text: str) -> str:
    """GitHub's heading anchors: lowercase, spaces to -, punctuation dropped."""
    out = "".join(c for c in text.lower() if c.isalnum() or c in " -_")
    return out.replace(" ", "-")


def command_sections(prog: str, parser: argparse.ArgumentParser, level: int = 2) -> list[str]:
    lines: list[str] = []
    for name, sub in _subparsers(parser):
        title = f"{prog} {name}"
        children = _subparsers(sub)
        lines += [f"{'#' * level} `{title}`", ""]
        about = _help_of(parser, name)
        if about:
            lines += [about[0].upper() + about[1:] + ".", ""]
        lines += ["```text", sub.format_usage().strip().removeprefix("usage: "), "```", ""]
        rows = _arguments(sub)
        if rows:
            lines += ["| Argument | | Meaning |", "|---|---|---|"]
            lines += [f"| {a} | {r} | {m} |" for a, r, m in rows]
            lines.append("")
        if children:
            lines += command_sections(title, sub, level + 1)
    return lines


def cli_page() -> str:
    server = build_parser()
    client = client_parser()
    head = [
        "# Command reference",
        "",
        "Every command and flag of the two command-line tools, generated from their code.",
        "",
        "- [`jezero`](#jezero): the server, its maintenance commands and the commands for "
        "people (installed with the package).",
        "- [`jezero_client.py`](#jezero_clientpy): the client core that every plugin "
        "carries (one Python file, standard library only).",
        "",
        "## `jezero`",
        "",
        " ".join((server.description or "").split()),
        "",
        "Global options, before the command:",
        "",
        "| Option | Meaning |",
        "|---|---|",
        "| `-c`, `--config` `CONFIG` | Path to `jezero.toml`. Default: `$JEZERO_CONFIG`, "
        "then `./jezero.toml`. |",
        "| `--version` | Print the version and exit. |",
        "",
        "Without a command, in a terminal, `jezero` opens [the app](../how-to/app.md).",
        "",
    ]
    body = command_sections("jezero", server, 3)
    client_head = [
        "## `jezero_client.py`",
        "",
        " ".join((client.description or "").split()),
        "Run it with `python3`; it needs Python 3.9 or newer and nothing else. See "
        "[the client reference](client.md) for its files and environment variables.",
        "",
    ]
    client_body = command_sections("jezero_client.py", client, 3)
    toc = ["## Contents", ""]
    for prog, parser in (("jezero", server), ("jezero_client.py", client)):
        names = ", ".join(f"[`{n}`](#{_anchor(f'{prog} {n}')})" for n, _ in _subparsers(parser))
        toc += [f"- `{prog}`: {names}"]
    toc.append("")
    return NOTE + "\n".join(head[:7] + toc + head[7:] + body + client_head + client_body)


# ------------------------------------------------------------------------ configuration


def _type_name(annotation: Any) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin in (typing.Union, types.UnionType):
        names = [_type_name(a) for a in args if a is not type(None)]
        return " or ".join(names) + (" (optional)" if type(None) in args else "")
    if origin is typing.Literal:
        return " \\| ".join(f'`"{a}"`' for a in args)
    if origin in (list, typing.List):  # noqa: UP006
        return f"list of {_type_name(args[0])}" if args else "list"
    if origin in (dict, typing.Dict):  # noqa: UP006
        return "table" if not args else f"table of {_type_name(args[1])}"
    if annotation is Path:
        return "path"
    if annotation is Any:
        return "any"
    if isinstance(annotation, type):
        return {"str": "string", "int": "integer", "float": "number", "bool": "boolean"}.get(
            annotation.__name__, annotation.__name__
        )
    return str(annotation)


def _default(field: FieldInfo) -> str:
    if field.default_factory is not None:
        value = field.default_factory()  # type: ignore[call-arg]
        if isinstance(value, BaseModel):
            return ""
    elif field.default is PydanticUndefined:
        return "required"
    else:
        value = field.default
    if value is None:
        return "none"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, str | Path):
        return f'`"{value}"`'
    if value == [] or value == {}:
        return "empty"
    return f"`{value}`"


def _limits(field: FieldInfo) -> str:
    bits = []
    for meta in field.metadata:
        for attr, sign in (("ge", "≥"), ("gt", ">"), ("le", "≤"), ("lt", "<")):
            if getattr(meta, attr, None) is not None:
                bits.append(f"{sign} {getattr(meta, attr)}")
    return f" ({', '.join(bits)})" if bits else ""


TABLES: dict[str, tuple[type[BaseModel], str, bool]] = {
    "storage": (cfg.StorageConfig, "Where the library lives.", False),
    "search": (cfg.SearchConfig, "How results are ranked and how many come back.", False),
    "summarizer": (cfg.SummarizerConfig, "The model that writes each item.", False),
    "server": (cfg.ServerConfig, "The MCP server and its HTTP routes.", False),
    "clients": (cfg.ClientConfig, "Who may read (and upload). One block per key.", True),
    "connectors": (cfg.ConnectorConfig, "Where items come from. One block per source.", True),
    "inbox": (cfg.InboxConfig, "Where uploaded sessions land.", False),
    "projects": (cfg.ProjectsConfig, "How a session's folder maps to a project.", False),
    "redaction": (cfg.RedactionConfig, "What is removed before anything is stored.", False),
    "watchdog": (cfg.WatchdogConfig, "When `jezero health` raises an alarm.", False),
}


def config_page() -> str:
    lines = [
        "# Configuration reference",
        "",
        "Every key of `jezero.toml`, generated from the configuration models. A complete,",
        "commented example lives in [`jezero.example.toml`](../../jezero.example.toml).",
        "",
        "Jezero reads the file given with `--config`, else `$JEZERO_CONFIG`, else",
        "`./jezero.toml`, and loads a `.env` file next to it (variables already set win).",
        "Relative paths are relative to the file. Unknown keys are an error, so a typo never",
        "goes unnoticed.",
        "",
        "> [!NOTE]",
        "> Secrets never go in this file. Keys ending in `_env` hold the *name* of an",
        "> environment variable, and an option that looks like a secret without `_env` is",
        "> rejected.",
        "",
        "| Table | |",
        "|---|---|",
    ]
    for name, (_, about, many) in TABLES.items():
        table = f"[[{name}]]" if many else f"[{name}]"
        lines.append(f"| [`{table}`](#{name}) | {about} |")
    lines.append("")
    for name, (model, about, many) in TABLES.items():
        lines += [f"## {name}", "", about]
        doc = " ".join((model.__doc__ or "").split())
        if doc and not doc.startswith(model.__name__):
            lines += ["", doc]
        lines += [
            "",
            "```toml",
            f"[[{name}]]" if many else f"[{name}]",
            "```",
            "",
            "| Key | Type | Default | Meaning |",
            "|---|---|---|---|",
        ]
        for key, field in model.model_fields.items():
            if field.exclude:
                continue
            meaning = " ".join((field.description or "").split())
            lines.append(
                f"| `{key}` | {_type_name(field.annotation)}{_limits(field)} | "
                f"{_default(field)} | {meaning} |"
            )
        lines.append("")
    lines += [
        "## See also",
        "",
        "- [Connectors](connectors.md): the `options` of each connector type.",
        "- [Add and tune sources](../how-to/sources.md): connectors in practice.",
        "- [Manage computers and keys](../how-to/devices.md): `[[clients]]` in practice.",
        "",
    ]
    return NOTE + "\n".join(lines)


def main() -> int:
    pages = {OUT / "cli.md": cli_page(), OUT / "configuration.md": config_page()}
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in pages.items() if not p.is_file() or p.read_text() != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run scripts/make_reference.py")
        if not stale:
            print("generated reference pages are up to date")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in pages.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
